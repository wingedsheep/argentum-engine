/**
 * The in-game settings dialog: the same PreferencesPanel as /preferences, over the board, so a
 * player can change stacking or add a stop without leaving the game. Battlefield and display
 * changes apply live; stops apply to this game too (see the subscription in gameStore.ts).
 */
import { useEffect } from 'react'
import { createPortal } from 'react-dom'
import { PreferencesPanel } from './PreferencesPanel'
import d from './PreferencesDialog.module.css'

export function PreferencesDialog({ onClose }: { onClose: () => void }) {
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') {
        e.stopPropagation()
        onClose()
      }
    }
    window.addEventListener('keydown', onKey, true)
    return () => window.removeEventListener('keydown', onKey, true)
  }, [onClose])

  return createPortal(
    <div className={d.backdrop} onPointerDown={(e) => { if (e.target === e.currentTarget) onClose() }}>
      <div className={d.dialog} role="dialog" aria-modal="true" aria-labelledby="preferences-dialog-title">
        <header className={d.head}>
          <h2 id="preferences-dialog-title" className={d.title}>Preferences</h2>
          <button type="button" className={d.close} onClick={onClose} aria-label="Close preferences">
            <svg viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" aria-hidden>
              <path d="M6 6l12 12M18 6L6 18" />
            </svg>
          </button>
        </header>
        <div className={d.body}>
          <PreferencesPanel compact />
        </div>
      </div>
    </div>,
    document.body,
  )
}

