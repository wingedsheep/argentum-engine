package com.wingedsheep.engine.mechanics.layers

import com.wingedsheep.engine.state.GameState
import com.wingedsheep.sdk.core.Keyword

/**
 * Sorts continuous effects by layer, sublayer, dependency, and timestamp (Rule 613).
 */
internal class EffectSorter {

    fun sortByLayerAndDependency(
        effects: List<ContinuousEffect>,
        state: GameState
    ): List<ContinuousEffect> {
        val byLayer = effects.groupBy { it.layer }
        val result = mutableListOf<ContinuousEffect>()

        for (layer in Layer.entries) {
            val layerEffects = byLayer[layer] ?: continue

            if (layer == Layer.POWER_TOUGHNESS) {
                val bySublayer = layerEffects.groupBy { it.sublayer }
                for (sublayer in Sublayer.entries) {
                    val sublayerEffects = bySublayer[sublayer] ?: continue
                    result.addAll(sortByDependencyAndTimestamp(sublayerEffects, state))
                }
            } else {
                result.addAll(sortByDependencyAndTimestamp(layerEffects, state))
            }
        }

        return result
    }

    private fun sortByDependencyAndTimestamp(
        effects: List<ContinuousEffect>,
        state: GameState
    ): List<ContinuousEffect> {
        if (effects.size <= 1) return effects

        val dependencies = mutableMapOf<ContinuousEffect, Set<ContinuousEffect>>()

        for (effectA in effects) {
            val dependsOn = mutableSetOf<ContinuousEffect>()
            val readKeywords = effectA.affectsFilter?.let(::keywordsReadBy).orEmpty()
            for (effectB in effects) {
                if (effectA === effectB) continue
                if (dependsOn(effectA, effectB, readKeywords, state)) {
                    dependsOn.add(effectB)
                }
            }
            dependencies[effectA] = dependsOn
        }

        // Topological sort with timestamp as tiebreaker
        // Use identity-based tracking to avoid deduplicating equal-but-distinct effects
        val result = mutableListOf<ContinuousEffect>()
        val remaining = effects.toMutableList()

        while (remaining.isNotEmpty()) {
            val ready = remaining.filter { effect ->
                dependencies[effect]?.none { dep -> remaining.any { it === dep } } ?: true
            }.sortedBy { it.timestamp }

            if (ready.isEmpty()) {
                result.addAll(remaining.sortedBy { it.timestamp })
                break
            }

            val next = ready.first()
            result.add(next)
            remaining.removeAt(remaining.indexOfFirst { it === next })
        }

        return result
    }

    private fun dependsOn(
        effectA: ContinuousEffect,
        effectB: ContinuousEffect,
        readKeywords: Set<Keyword>,
        state: GameState
    ): Boolean {
        // Type-changing effects: any effect that changes types, subtypes, or land types
        // creates a dependency for other effects sharing those entities, because changing
        // types can change what other effects apply to or what they accomplish.
        // This covers Blood Moon + Urborg: SetBasicLandTypes on Urborg changes what
        // Urborg's AddSubtype effect does (it ceases to exist once Urborg is a Mountain).
        if (effectB.modification is Modification.AddType ||
            effectB.modification is Modification.RemoveType ||
            effectB.modification is Modification.SetBasicLandTypes ||
            effectB.modification is Modification.SetBasicLandTypesFromChosen ||
            effectB.modification is Modification.SetCardTypes ||
            effectB.modification is Modification.SetAllSubtypes ||
            effectB.modification is Modification.SetCreatureSubtypes ||
            effectB.modification is Modification.SetCreatureSubtypesFrom ||
            effectB.modification is Modification.AddSubtype ||
            effectB.modification is Modification.RemoveSubtype) {
            return effectA.affectedEntities.any { it in effectB.affectedEntities }
        }
        // Independent grants (e.g. bestow's enchant ability) are not regenerated by their source.
        // A later ability removal must erase them; keep timestamp order for those grants.
        // A static grant also depends on a removal that strips its *source* (CR 613.8a: applying
        // the removal changes the grant's existence) — StateProjector then drops the grant.
        if (effectA.fromStaticAbility && effectB.modification is Modification.RemoveAllAbilities &&
            (effectA.modification is Modification.GrantKeyword || effectA.modification is Modification.GrantStaticAbility)) {
            if (effectA.sourceId in effectB.affectedEntities ||
                effectA.affectedEntities.any { it in effectB.affectedEntities }) return true
            // A holder's effect from a granted static also exists only while its *granter* keeps
            // its abilities (a Rune stripped of its abilities stops the Equipment's trample).
            if (effectA.grantedBy != null && effectA.grantedBy in effectB.affectedEntities) return true
        }
        // An effect whose affected set reads keywords ("creatures with flying have vigilance")
        // depends on a same-layer effect that grants or removes one of those keywords
        // (CR 613.8a): applying that one changes what this one applies to. StateProjector
        // re-resolves the keyword-reading set when it applies.
        if (readKeywords.isNotEmpty() && changesKeywords(effectB.modification, readKeywords)) return true
        return false
    }

    private fun changesKeywords(modification: Modification, keywords: Set<Keyword>): Boolean = when (modification) {
        is Modification.GrantKeyword -> keywords.any { modification.keyword.isKeyword(it) }
        is Modification.RemoveKeyword -> keywords.any { modification.keyword.isKeyword(it) }
        Modification.RemoveAllAbilities,
        Modification.GrantLandwalkFromChosen,
        is Modification.GrantKeywordsOfCards -> true
        else -> false
    }

    /** Whether a projected keyword string is [keyword], bare or numeric (`RAMPAGE_2`) — see [containsKeyword]. */
    private fun String.isKeyword(keyword: Keyword): Boolean =
        this == keyword.name || (startsWith("${keyword.name}_") && length > keyword.name.length + 1 &&
            substring(keyword.name.length + 1).all(Char::isDigit))
}
