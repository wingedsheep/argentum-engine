/**
 * "Spend this mana only to cast Dragon spells or activate abilities of Dragons."
 *
 *  - the spell side is any spell with the Dragon subtype ([ManaRestriction.SubtypeSpellsOnly]). A
 *    face-down spell has no subtypes, and turning a permanent face up is a special action rather
 *    than a spell or an ability, so neither is admitted (2014-11-24 ruling).
 *  - the ability side is a Dragon *permanent*: per the 2014-11-24 ruling the mana can't pay for an
 *    ability of a Dragon source that isn't on the battlefield (a Dragon card's cycling from hand).
 *    A creature type only ever appears on a creature or kindred object (CR 205.3d), so "a source on
 *    the battlefield that is a creature or kindred" plus "is a Dragon" is exactly "an ability of a
 *    Dragon" permanent — Base Camp's shape. The card-type atoms disable their spell side, so that
 *    branch only ever admits ability activations.
 */
private val dragonSpend = ManaRestriction.AnyOf(
    listOf(
        ManaRestriction.SubtypeSpellsOnly(setOf("Dragon")),
        ManaRestriction.AllOf(
            listOf(
                ManaRestriction.AnyOf(
                    listOf(CardType.CREATURE, CardType.KINDRED).map { type ->
                        ManaRestriction.CardTypeSpellsOrAbilitiesOnly(
                            cardType = type,
                            allowSpells = false,
                            allowAbilities = true,
                            permanentSourcesOnly = true,
                        )
                    }
                ),
                ManaRestriction.SubtypeSpellsOrAbilitiesOnly("Dragon"),
            )
        ),
    )
)

/**
 * Crucible of the Spirit Dragon
 * Land
 * {T}: Add {C}.
 * {1}, {T}: Put a storage counter on this land.
 * {T}, Remove X storage counters from this land: Add X mana in any combination of colors. Spend
 * this mana only to cast Dragon spells or activate abilities of Dragons.
 *
 * The storage-land shape (Mage-Ring Network): the last ability is a mana ability whose self-scoped
 * variable counter-removal cost feeds its X into the amount of any-combination mana produced
 * (one color choice per pip), every unit carrying [dragonSpend].
 */
val CrucibleOfTheSpiritDragon = card("Crucible of the Spirit Dragon") {
    typeLine = "Land"
    colorIdentity = ""
    oracleText = "{T}: Add {C}.\n" +
        "{1}, {T}: Put a storage counter on this land.\n" +
        "{T}, Remove X storage counters from this land: Add X mana in any combination of colors. " +
        "Spend this mana only to cast Dragon spells or activate abilities of Dragons."

    activatedAbility {
        cost = Costs.Tap
        effect = Effects.AddColorlessMana(1)
        manaAbility = true
        timing = TimingRule.ManaAbility
    }

    activatedAbility {
        cost = Costs.Composite(Costs.Mana("{1}"), Costs.Tap)
        effect = Effects.AddCounters(CounterType.STORAGE, 1, EffectTarget.Self)
        description = "{1}, {T}: Put a storage counter on this land."
    }

    activatedAbility {
        cost = Costs.Composite(
            Costs.Tap,
            Costs.RemoveXCounters(counterType = CounterType.STORAGE, self = true),
        )
        effect = Effects.AddManaInAnyCombination(DynamicAmounts.xValue(), restriction = dragonSpend)
        manaAbility = true
        timing = TimingRule.ManaAbility
        description = "{T}, Remove X storage counters from this land: Add X mana in any combination of " +
            "colors. Spend this mana only to cast Dragon spells or activate abilities of Dragons."
    }

    metadata {
        rarity = Rarity.RARE
        collectorNumber = "167"
        artist = "Jung Park"
        imageUri = "https://cards.scryfall.io/normal/front/6/b/6bf563e0-1f42-4768-a667-3e120bdb6534.jpg?1783938669"
        ruling("2014-11-24", "You can use mana generated by the last ability to pay an alternative cost (such as a dash cost) or an additional cost to cast a Dragon spell. It's not limited to paying just that spell's mana cost.")
        ruling("2014-11-24", "Notably, turning a face-down creature face up isn't an activated ability. If you manifest a Dragon creature card or cast a Dragon creature card face down using the morph ability, you can't use mana generated by the last ability to turn that card face up.")
        ruling("2014-11-24", "The mana generated by the last ability can't be spent to activate abilities of Dragon sources that aren't on the battlefield.")
    }
}
