package com.wingedsheep.mtg.sets.definitions.bng.cards

import com.wingedsheep.sdk.core.Keyword
import com.wingedsheep.sdk.dsl.card
import com.wingedsheep.sdk.model.Rarity
import com.wingedsheep.sdk.scripting.GrantKeyword
import com.wingedsheep.sdk.scripting.RemoveKeywordStatic
import com.wingedsheep.sdk.scripting.filters.unified.GroupFilter

/**
 * Archetype of Courage
 * {1}{W}{W}
 * Enchantment Creature — Human Soldier
 * 2/2
 *
 * Creatures you control have first strike.
 * Creatures your opponents control lose first strike and can't have or gain first strike.
 *
 * The second ability is [RemoveKeywordStatic] with `cantHaveOrGain`: it beats every grant whatever
 * its timestamp, and a resolving grant made while it applies is never created for those creatures.
 */
val ArchetypeOfCourage = card("Archetype of Courage") {
    manaCost = "{1}{W}{W}"
    colorIdentity = "W"
    typeLine = "Enchantment Creature — Human Soldier"
    power = 2
    toughness = 2
    oracleText = "Creatures you control have first strike.\nCreatures your opponents control lose first strike and can't have or gain first strike."

    staticAbility {
        ability = GrantKeyword(Keyword.FIRST_STRIKE, GroupFilter.AllCreaturesYouControl)
    }

    staticAbility {
        ability = RemoveKeywordStatic(Keyword.FIRST_STRIKE, GroupFilter.AllCreaturesOpponentsControl, cantHaveOrGain = true)
    }

    metadata {
        rarity = Rarity.UNCOMMON
        collectorNumber = "4"
        artist = "Willian Murai"
        flavorText = "\"It has been my experience that soldiers most fervently follow generals who lead by example.\" —Elspeth"
        imageUri = "https://cards.scryfall.io/normal/front/8/e/8e6c4afb-6a94-4519-91c6-9824fed2892c.jpg?1783939584"
        ruling(
            "2014-02-01",
            "The Archetype's second ability applies to each creature controlled by any of your opponents, no matter when it entered the battlefield."
        )
        ruling(
            "2014-02-01",
            "While you control an Archetype, continuous effects generated by the resolution of spells and abilities that would give the specified ability to creatures your opponents control aren't created. For example, if you control Archetype of Courage, a spell cast by an opponent that gives creatures they control first strike wouldn't cause the creatures to have first strike, even if later in the turn Archetype of Courage left the battlefield. (If the spell has additional effects, such as raising the power of the creatures, those effects will apply as normal.)"
        )
        ruling(
            "2014-02-01",
            "Conversely, continuous effects generated by static abilities (such as an Aura that granted the appropriate ability) would resume applying if the Archetype left the battlefield."
        )
        ruling(
            "2014-02-01",
            "If you and an opponent each control the same Archetype, no creature controlled by any player will have the appropriate ability."
        )
    }
}
