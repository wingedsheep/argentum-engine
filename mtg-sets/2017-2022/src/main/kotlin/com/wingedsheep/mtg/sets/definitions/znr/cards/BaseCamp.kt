package com.wingedsheep.mtg.sets.definitions.znr.cards

import com.wingedsheep.sdk.core.CardType
import com.wingedsheep.sdk.dsl.Costs
import com.wingedsheep.sdk.dsl.Effects
import com.wingedsheep.sdk.dsl.card
import com.wingedsheep.sdk.model.Rarity
import com.wingedsheep.sdk.scripting.EntersTapped
import com.wingedsheep.sdk.scripting.TimingRule
import com.wingedsheep.sdk.scripting.effects.ManaRestriction

private val PARTY_TYPES = listOf("Cleric", "Rogue", "Warrior", "Wizard")

/**
 * "Spend this mana only to cast a Cleric, Rogue, Warrior, or Wizard spell or to activate an
 * ability of a Cleric, Rogue, Warrior, or Wizard."
 *
 * Two spend contexts joined by "or":
 *  - the spell side is [ManaRestriction.SubtypeSpellsOnly] over the four party types;
 *  - the ability side is a party-typed *permanent*. Per the ruling, the mana can't pay for an
 *    ability of a card that isn't on the battlefield (a Wizard's graveyard or hand ability). A
 *    creature type only ever appears on a creature or kindred object (CR 205.3d), so "a source on
 *    the battlefield that is a creature or kindred" plus "has a party type" is exactly "an ability
 *    of a Cleric, Rogue, Warrior, or Wizard" permanent. The spell-side atoms are disabled
 *    (`allowSpells = false`), so this branch only ever admits ability activations.
 */
private val partySpend = ManaRestriction.AnyOf(
    listOf(
        ManaRestriction.SubtypeSpellsOnly(PARTY_TYPES.toSet()),
        ManaRestriction.AllOf(
            listOf(
                ManaRestriction.AnyOf(
                    listOf(CardType.CREATURE, CardType.KINDRED).map { type ->
                        ManaRestriction.CardTypeSpellsOrAbilitiesOnly(
                            cardType = type,
                            allowSpells = false,
                            allowAbilities = true,
                            permanentSourcesOnly = true,
                        )
                    }
                ),
                ManaRestriction.AnyOf(
                    PARTY_TYPES.map { ManaRestriction.SubtypeSpellsOrAbilitiesOnly(it) }
                ),
            )
        ),
    )
)

/**
 * Base Camp — Zendikar Rising #257
 * Land
 *
 * This land enters tapped.
 * {T}: Add {C}.
 * {T}: Add one mana of any color. Spend this mana only to cast a Cleric, Rogue, Warrior, or Wizard
 * spell or to activate an ability of a Cleric, Rogue, Warrior, or Wizard.
 */
val BaseCamp = card("Base Camp") {
    typeLine = "Land"
    oracleText = "This land enters tapped.\n" +
        "{T}: Add {C}.\n" +
        "{T}: Add one mana of any color. Spend this mana only to cast a Cleric, Rogue, Warrior, " +
        "or Wizard spell or to activate an ability of a Cleric, Rogue, Warrior, or Wizard."

    replacementEffect(EntersTapped())

    activatedAbility {
        cost = Costs.Tap
        effect = Effects.AddColorlessMana(1)
        manaAbility = true
        timing = TimingRule.ManaAbility
    }

    activatedAbility {
        cost = Costs.Tap
        effect = Effects.AddAnyColorMana(1, restriction = partySpend)
        manaAbility = true
        timing = TimingRule.ManaAbility
    }

    metadata {
        rarity = Rarity.UNCOMMON
        collectorNumber = "257"
        artist = "Jokubas Uogintas"
        flavorText = "A new dawn, a new adventure."
        imageUri = "https://cards.scryfall.io/normal/front/d/c/dc85412e-333d-4e7d-8c85-40618cf1b6c2.jpg?1783929310"

        ruling(
            "2020-09-25",
            "The mana generated by Base Camp's last ability can't be spent to activate abilities of " +
                "cards that aren't on the battlefield or to pay a cost in a resolving triggered ability."
        )
    }
}
