package com.wingedsheep.mtg.sets.definitions.thb.cards

import com.wingedsheep.sdk.core.CardType
import com.wingedsheep.sdk.core.Keyword
import com.wingedsheep.sdk.dsl.Costs
import com.wingedsheep.sdk.dsl.Effects
import com.wingedsheep.sdk.dsl.card
import com.wingedsheep.sdk.model.Rarity
import com.wingedsheep.sdk.scripting.GameObjectFilter
import com.wingedsheep.sdk.scripting.GrantKeyword
import com.wingedsheep.sdk.scripting.TimingRule
import com.wingedsheep.sdk.scripting.effects.ManaRestriction
import com.wingedsheep.sdk.scripting.filters.unified.GroupFilter

/**
 * Dalakos, Crafter of Wonders
 * {1}{U}{R}
 * Legendary Creature — Merfolk Artificer
 * 2/4
 * {T}: Add {C}{C}. Spend this mana only to cast artifact spells or activate abilities of artifacts.
 * Equipped creatures you control have flying and haste.
 *
 * The mana ability is Renowned Weaponsmith's ([ManaRestriction.CardTypeSpellsOrAbilitiesOnly] over
 * artifacts). The grant is Firion's `Creature.youControl().equipped()` group — "equipped" means one
 * or more Equipment attached, so a creature that is itself an Equipment doesn't qualify (ruling).
 */
val DalakosCrafterOfWonders = card("Dalakos, Crafter of Wonders") {
    manaCost = "{1}{U}{R}"
    colorIdentity = "UR"
    typeLine = "Legendary Creature — Merfolk Artificer"
    power = 2
    toughness = 4
    oracleText = "{T}: Add {C}{C}. Spend this mana only to cast artifact spells or activate abilities of " +
        "artifacts.\n" +
        "Equipped creatures you control have flying and haste."

    activatedAbility {
        cost = Costs.Tap
        effect = Effects.AddColorlessMana(
            2,
            restriction = ManaRestriction.CardTypeSpellsOrAbilitiesOnly(
                cardType = CardType.ARTIFACT,
                allowSpells = true,
                allowAbilities = true,
            )
        )
        manaAbility = true
        timing = TimingRule.ManaAbility
    }

    staticAbility {
        ability = GrantKeyword(Keyword.FLYING, GroupFilter(GameObjectFilter.Creature.youControl().equipped()))
    }

    staticAbility {
        ability = GrantKeyword(Keyword.HASTE, GroupFilter(GameObjectFilter.Creature.youControl().equipped()))
    }

    metadata {
        rarity = Rarity.RARE
        collectorNumber = "212"
        artist = "Ryan Pancoast"
        flavorText = "His imagination soars from the depths of the sea to the heights of the heavens."
        imageUri = "https://cards.scryfall.io/normal/front/5/7/57ea0ba2-3ccf-4313-ad1d-161272c48851.jpg?1783931524"
        ruling(
            "2020-01-24",
            "You can't spend mana generated by Dalakos's first ability to activate abilities of artifact " +
                "cards that aren't on the battlefield or to pay costs in triggered abilities of artifacts."
        )
        ruling(
            "2020-01-24",
            "An equipped creature is one with one or more Equipment attached. A creature that's also an " +
                "Equipment isn't an equipped creature."
        )
    }
}
