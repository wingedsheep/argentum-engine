package com.wingedsheep.mtg.sets.definitions.eld.cards

import com.wingedsheep.sdk.core.CardType
import com.wingedsheep.sdk.core.Color
import com.wingedsheep.sdk.core.Zone
import com.wingedsheep.sdk.dsl.Costs
import com.wingedsheep.sdk.dsl.Effects
import com.wingedsheep.sdk.dsl.card
import com.wingedsheep.sdk.model.Rarity
import com.wingedsheep.sdk.scripting.EntersTapped
import com.wingedsheep.sdk.scripting.GameObjectFilter
import com.wingedsheep.sdk.scripting.TimingRule
import com.wingedsheep.sdk.scripting.conditions.Exists
import com.wingedsheep.sdk.scripting.effects.ManaRestriction
import com.wingedsheep.sdk.scripting.references.Player

/**
 * Castle Garenbrig
 *
 * Land
 * This land enters tapped unless you control a Forest.
 * {T}: Add {G}.
 * {2}{G}{G}, {T}: Add six {G}. Spend this mana only to cast creature spells or activate abilities
 * of creatures.
 *
 * Same entry clause as the rest of the Castle cycle (see [CastleVantress]). The six-{G} ability
 * is still a mana ability (no target, produces mana — CR 605.1a), so it resolves immediately
 * like the plain tap. Its spend restriction is [ManaRestriction.CardTypeSpellsOrAbilitiesOnly]
 * with `permanentSourcesOnly = true`: per the 2019-10-04 ruling the mana can't pay for abilities
 * of creature cards that aren't on the battlefield.
 */
val CastleGarenbrig = card("Castle Garenbrig") {
    manaCost = ""
    colorIdentity = "G"
    typeLine = "Land"
    oracleText = "This land enters tapped unless you control a Forest.\n" +
        "{T}: Add {G}.\n" +
        "{2}{G}{G}, {T}: Add six {G}. Spend this mana only to cast creature spells or activate " +
        "abilities of creatures."

    replacementEffect(
        EntersTapped(
            unlessCondition = Exists(
                Player.You,
                Zone.BATTLEFIELD,
                GameObjectFilter.Land.withSubtype("Forest"),
            )
        )
    )

    // {T}: Add {G}.
    activatedAbility {
        cost = Costs.Tap
        effect = Effects.AddMana(Color.GREEN)
        manaAbility = true
        timing = TimingRule.ManaAbility
    }

    // {2}{G}{G}, {T}: Add six {G}. Spend this mana only to cast creature spells or activate
    // abilities of creatures.
    activatedAbility {
        cost = Costs.Composite(Costs.Mana("{2}{G}{G}"), Costs.Tap)
        effect = Effects.AddMana(
            Color.GREEN,
            amount = 6,
            restriction = ManaRestriction.CardTypeSpellsOrAbilitiesOnly(
                cardType = CardType.CREATURE,
                allowAbilities = true,
                permanentSourcesOnly = true,
            ),
        )
        manaAbility = true
        timing = TimingRule.ManaAbility
        description = "{2}{G}{G}, {T}: Add six {G}. Spend this mana only to cast creature spells " +
            "or activate abilities of creatures."
    }

    metadata {
        rarity = Rarity.RARE
        collectorNumber = "240"
        artist = "Adam Paquette"
        flavorText = "Without Garenbrig's strength, the realm would succumb to the wilds."
        imageUri = "https://cards.scryfall.io/normal/front/e/3/e3c2c66c-f7f0-41d5-a805-a129aeaf1b75.jpg?1783932578"
        ruling(
            "2019-10-04",
            "The mana generated by Castle Garenbrig's last ability can't be spent to activate " +
                "abilities of creature cards that aren't on the battlefield.",
        )
    }
}
