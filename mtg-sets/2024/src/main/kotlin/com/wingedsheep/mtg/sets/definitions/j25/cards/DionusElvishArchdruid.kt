package com.wingedsheep.mtg.sets.definitions.j25.cards

import com.wingedsheep.sdk.core.CounterType
import com.wingedsheep.sdk.core.Subtype
import com.wingedsheep.sdk.dsl.Conditions
import com.wingedsheep.sdk.dsl.Effects
import com.wingedsheep.sdk.dsl.Triggers
import com.wingedsheep.sdk.dsl.card
import com.wingedsheep.sdk.model.Rarity
import com.wingedsheep.sdk.scripting.GameObjectFilter
import com.wingedsheep.sdk.scripting.GrantTriggeredAbility
import com.wingedsheep.sdk.scripting.TriggeredAbility
import com.wingedsheep.sdk.scripting.filters.unified.GroupFilter
import com.wingedsheep.sdk.scripting.targets.EffectTarget

/**
 * Dionus, Elvish Archdruid — Foundations Jumpstart #52
 * {3}{G} · Legendary Creature — Elf Druid · 3/3
 *
 * Elves you control have "Whenever this creature becomes tapped during your turn, untap it and put
 * a +1/+1 counter on it. This ability triggers only once each turn."
 *
 * - Tyvar the Bellicose's shape: a [GrantTriggeredAbility] carrying a once-per-turn trigger. The
 *   engine gives a capped granted ability its own id per granting object (and per object
 *   generation), so two Dionuses grant two independent abilities, and a Dionus that leaves and
 *   returns grants a fresh one (rulings). Dionus is an Elf, so it grants the ability to itself.
 * - "During your turn" restricts the trigger event ([TriggeredAbility.triggerRestriction]),
 *   checked once when it would trigger, not again on resolution.
 * - A permanent that enters tapped never "becomes tapped", so it doesn't trigger (ruling); the
 *   untap is a no-op if it's already untapped by resolution, but the counter is still placed.
 */
val DionusElvishArchdruid = card("Dionus, Elvish Archdruid") {
    manaCost = "{3}{G}"
    colorIdentity = "G"
    typeLine = "Legendary Creature — Elf Druid"
    power = 3
    toughness = 3
    oracleText = "Elves you control have \"Whenever this creature becomes tapped during your turn, " +
        "untap it and put a +1/+1 counter on it. This ability triggers only once each turn.\""

    staticAbility {
        ability = GrantTriggeredAbility(
            ability = TriggeredAbility.create(
                trigger = Triggers.self.becomesTapped(),
                effect = Effects.Untap(EffectTarget.Self) then
                    Effects.AddCounters(CounterType.PLUS_ONE_PLUS_ONE, 1, EffectTarget.Self),
                triggerRestriction = Conditions.IsYourTurn,
                oncePerTurn = true,
            ),
            filter = GroupFilter(GameObjectFilter.Permanent.withSubtype(Subtype.ELF).youControl()),
        )
    }

    metadata {
        rarity = Rarity.UNCOMMON
        collectorNumber = "52"
        artist = "BODAX"
        flavorText = "\"My people are like the great magnigoth trees. We've seen ice, flood, invasions, " +
            "and wars, yet our roots remain strong.\""
        imageUri = "https://cards.scryfall.io/normal/front/5/a/5a3dfd71-9ec0-4842-b99d-c1833679f0c5.jpg?1783908855"
        ruling("2024-11-08", "Dionus's ability grants a triggered ability to itself as well as other Elves you control.")
        ruling("2024-11-08", "A permanent that enters tapped doesn't \"become tapped.\" As such, if it has the ability granted by Dionus, that ability won't trigger.")
        ruling("2024-11-08", "If Dionus leaves the battlefield while one or more triggered abilities generated by the ability it grants are still on the stack, those abilities will still resolve as normal.")
        ruling("2024-11-08", "If you somehow control multiple copies of Dionus, each permanent you control will have that many instances of the granted ability. These abilities are not redundant. For example, if you control two copies of Dionus and one becomes tapped during your turn, each of its granted abilities will trigger. When those abilities resolve, each one will untap that Dionus (if it's tapped at the time) and will put a +1/+1 counter on it regardless of whether it's tapped or untapped.")
        ruling("2024-11-08", "If Dionus leaves the battlefield and returns to the battlefield in the same turn, or if one Dionus leaves and another Dionus enters, the ability granted by the old one is different from the ability granted by the new one. This means that an Elf that already untapped and got a +1/+1 counter from the previous granted triggered ability could untap and get another +1/+1 counter from the new granted triggered ability if it becomes tapped again later that turn.")
    }
}
