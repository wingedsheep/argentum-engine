package com.wingedsheep.sdk.surface

import io.kotest.core.spec.style.FunSpec
import java.io.File

/**
 * Keeps `docs/sdk-index.md` — one line per sealed SDK leaf, grouped by family: its name, its fields
 * and the first sentence of its KDoc — in step with the code. The hand-written catalog
 * (`docs/card-sdk-language-reference.md`) explains; this index is what you grep to find out whether a
 * type already exists, and what the closest one is called.
 *
 * Fails when the checked-in index is stale; `just sdk-index` (`-DupdateSdkIndex=true`) rewrites it.
 */
class SdkIndexTest : FunSpec({

    test("docs/sdk-index.md matches the SDK") {
        val file = File("../docs/sdk-index.md")
        val expected = SdkIndex.render(File("src/main/kotlin"))
        if (System.getProperty("updateSdkIndex") == "true") {
            file.writeText(expected)
        } else if (!file.exists() || file.readText() != expected) {
            error("docs/sdk-index.md is out of date with the SDK — run `just sdk-index` and commit the result.")
        }
    }
})

internal object SdkIndex {

    fun render(sdkSource: File): String {
        val docs = KDocIndex(sdkSource)
        return buildString {
            appendLine("# SDK index")
            appendLine()
            appendLine("<!-- Generated by `just sdk-index` from mtg-sdk (SdkIndexTest). Don't edit by hand. -->")
            appendLine()
            appendLine("Every concrete leaf of every sealed SDK family, one line each: name, fields, and the first")
            appendLine("sentence of its KDoc. Grep it to find whether a type exists and what its neighbours are")
            appendLine("called before adding one (`docs/sdk-design-principles.md`, \"Extend before you add\"). Cards")
            appendLine("reach these through facades (`Effects.*`, `Conditions.*`, `Filters.*`, …); the long-form")
            appendLine("catalog with authoring notes is [`card-sdk-language-reference.md`](card-sdk-language-reference.md).")
            appendLine()
            val families = SdkSurface.byFamily.entries.sortedWith(compareByDescending<Map.Entry<String, List<SdkSurface.Leaf>>> { it.value.size }.thenBy { it.key })
            appendLine("Families: " + families.joinToString(" · ") { "[${it.key}](#${anchor(it.key)}) (${it.value.size})" })
            for ((family, leaves) in families) {
                appendLine()
                appendLine("## ${family}")
                appendLine()
                for (leaf in leaves.sortedBy { it.name }) {
                    val fields = if (leaf.fields.isEmpty()) "" else "(${leaf.fields.joinToString()})"
                    val summary = docs.summary(leaf)?.let { " — $it" } ?: ""
                    appendLine("- `${leaf.name}$fields`$summary")
                }
            }
        }
    }

    private fun anchor(heading: String) = heading.lowercase().replace(Regex("[^a-z0-9 -]"), "").replace(' ', '-')
}

/** First KDoc sentence per declaration in the SDK source, keyed by simple name. */
private class KDocIndex(root: File) {

    private data class Decl(val file: File, val text: String, val summary: String?)

    private val byName: Map<String, List<Decl>>

    init {
        val decl = Regex("""(/\*\*(?:(?!\*/).)*?\*/)?\s*(?:@[\w.]+(?:\([^)]*\))?\s*)*(?:(?:public|internal|private|sealed|data|abstract|open|value)\s+)*(?:class|object|interface)\s+(\w+)""", RegexOption.DOT_MATCHES_ALL)
        val all = mutableMapOf<String, MutableList<Decl>>()
        root.walkTopDown().filter { it.isFile && it.extension == "kt" }.forEach { file ->
            val text = file.readText()
            decl.findAll(text).forEach { m ->
                all.getOrPut(m.groupValues[2]) { mutableListOf() } += Decl(file, text, firstSentence(m.groupValues[1]))
            }
        }
        byName = all
    }

    fun summary(leaf: SdkSurface.Leaf): String? {
        val candidates = byName[leaf.simpleName].orEmpty()
        if (candidates.size <= 1) return candidates.singleOrNull()?.summary
        // A nested leaf (`CardPredicate.PowerAtLeast`) lives in a file that declares its parent.
        val parent = leaf.name.substringBeforeLast('.', "").substringAfterLast('.')
        val inParentFile = candidates.filter { parent.isNotEmpty() && Regex("""(?:class|object|interface)\s+$parent\b""").containsMatchIn(it.text) }
        return (inParentFile.singleOrNull() ?: candidates.firstOrNull { it.summary != null })?.summary
    }

    private fun firstSentence(kdoc: String): String? {
        if (kdoc.isBlank()) return null
        val text = kdoc.removePrefix("/**").removeSuffix("*/").lines()
            .map { it.trim().removePrefix("*").trim() }
            .takeWhile { !it.startsWith("@") }
            .joinToString(" ")
            .replace(Regex("""\[([^\]]+)]"""), "$1")
            .replace(Regex("""\s+"""), " ")
            .trim()
        if (text.isEmpty()) return null
        val end = Regex("""(?<!e\.g)(?<!i\.e)(?<!\bvs)[.!?](?=\s|$)""").find(text)?.range?.first
        val sentence = if (end != null) text.substring(0, end + 1) else text
        return if (sentence.length <= 200) sentence else sentence.take(197).trimEnd() + "…"
    }
}
